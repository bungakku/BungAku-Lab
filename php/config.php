<?php
/** Writes $WP_DIR/wp-config.php from the lab environment. Called by `lab up`; idempotent. */
$wp    = getenv( 'WP_DIR' );
$state = getenv( 'STATE_DIR' );
$url   = getenv( 'LAB_URL' );
$mode  = getenv( 'DB_MODE' ) ?: 'own';
@mkdir( $state, 0777, true );

$salts_file = "$state/salts.json";
if ( ! is_file( $salts_file ) ) {
	$salts = array();
	foreach ( array( 'AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT' ) as $k ) {
		$salts[ $k ] = bin2hex( random_bytes( 32 ) );
	}
	$salts['LAB_LOGIN_TOKEN'] = bin2hex( random_bytes( 16 ) );
	file_put_contents( $salts_file, json_encode( $salts ) );
}
$salts = json_decode( file_get_contents( $salts_file ), true );

$db_host = ( 'own' === $mode ) ? 'localhost:' . getenv( 'DB_SOCKET' ) : ( getenv( 'DB_HOST' ) ?: '127.0.0.1' ) . ':' . ( getenv( 'DB_PORT' ) ?: '3306' );
$allow   = getenv( 'LAB_ALLOW_HTTP' ) ? 'false' : 'true';

$c  = "<?php\n// Generated by BungAku-Lab (`bin/lab up` rewrites this file). Do not edit.\n";
$c .= 'define( "DB_NAME", ' . var_export( getenv( 'DB_NAME' ) ?: 'wp', true ) . " );\n";
$c .= 'define( "DB_USER", ' . var_export( getenv( 'DB_USER' ) ?: 'wp', true ) . " );\n";
$c .= 'define( "DB_PASSWORD", ' . var_export( getenv( 'DB_PASS' ) ?: 'wp', true ) . " );\n";
$c .= 'define( "DB_HOST", ' . var_export( $db_host, true ) . " );\n";
$c .= "define( 'DB_CHARSET', 'utf8mb4' );\ndefine( 'DB_COLLATE', '' );\n";
foreach ( $salts as $k => $v ) {
	$c .= 'define( ' . var_export( $k, true ) . ', ' . var_export( $v, true ) . " );\n";
}
$c .= "\$table_prefix = 'wp_';\n";
$c .= 'define( "WP_HOME", ' . var_export( $url, true ) . " );\ndefine( 'WP_SITEURL', WP_HOME );\n";
$c .= "define( 'WP_ENVIRONMENT_TYPE', 'local' );\n";
$c .= "define( 'WP_MEMORY_LIMIT', '256M' );\n";
$c .= "define( 'WP_DEBUG', true );\ndefine( 'WP_DEBUG_DISPLAY', false );\n";
$c .= 'define( "WP_DEBUG_LOG", ' . var_export( getenv( 'REPORT_DIR' ) . '/debug.log', true ) . " );\n";
$c .= "@ini_set( 'display_errors', '0' );\n";
$c .= "define( 'DISABLE_WP_CRON', true );\ndefine( 'AUTOMATIC_UPDATER_DISABLED', true );\ndefine( 'WP_AUTO_UPDATE_CORE', false );\n";
$c .= "define( 'FS_METHOD', 'direct' );\n";
$c .= "// No calls home: update checks and API requests are blocked unless LAB_ALLOW_HTTP=1.\n";
$c .= "define( 'WP_HTTP_BLOCK_EXTERNAL', $allow );\n";
$c .= 'define( "LAB_STATE_DIR", ' . var_export( $state, true ) . " );\n";
$c .= "if ( ! defined( 'ABSPATH' ) ) {\n\tdefine( 'ABSPATH', __DIR__ . '/' );\n}\nrequire_once ABSPATH . 'wp-settings.php';\n";

$target = "$wp/wp-config.php";
if ( ! is_file( $target ) || file_get_contents( $target ) !== $c ) {
	file_put_contents( $target, $c );
}
echo "wp-config ok\n";
